
"""Compare V1 and V3 Random Forests on matched fold-9 ECGs.

Both models use identical training settings and patient-aware
calibration. Their training populations remain different.

Fold 10 is not evaluated. Deployed models are unchanged.
"""

import json
from datetime import datetime, timezone
from pathlib import Path

import joblib
import numpy as np
import pandas as pd

from scripts.train_v3_rf_candidate import (
    ROOT,
    DATASET as V3_DATASET,
    CONTRACT as V3_DATASET_CONTRACT,
    MANIFEST,
    MODEL_PATH as V3_MODEL,
    REPORT_PATH as V3_REPORT,
    calculate_metrics,
    git_commit,
    sha256_file,
    split_name,
    train_candidate,
    verify_contract,
    verify_dataset,
)
from src.features.extract_features import FEATURE_COLUMNS


V1_DATASET = ROOT / "data/processed/clinical_features_validated.csv"

V1_MODEL = (
    ROOT / "models/checkpoints/interpretable_model_v1_grouped_comparator.joblib"
)

REPORT = ROOT / "docs/model_contracts/v1_v3_matched_fold9.json"

PREDICTIONS = (
    ROOT / "docs/model_contracts/v1_v3_matched_fold9_predictions.csv"
)


def load_v1_partitions():
    """Attach authoritative patient IDs to the V1 feature dataset."""

    frame = pd.read_csv(V1_DATASET)
    manifest = pd.read_csv(MANIFEST)

    required = {
        "ecg_id", "target_label", "strat_fold", *FEATURE_COLUMNS,
    }

    if not required.issubset(frame.columns):
        raise ValueError("V1 dataset has missing columns")

    if frame["ecg_id"].isna().any() or not frame["ecg_id"].is_unique:
        raise ValueError("Invalid V1 ECG identifiers")

    if manifest["ecg_id"].isna().any() or not manifest["ecg_id"].is_unique:
        raise ValueError("Invalid cohort manifest identifiers")

    indexed = manifest.set_index("ecg_id")

    if not frame["ecg_id"].isin(indexed.index).all():
        raise ValueError("V1 dataset contains unknown ECG IDs")

    metadata = indexed.loc[frame["ecg_id"]]

    for name in ("target_label", "strat_fold"):
        if not np.array_equal(
            frame[name].to_numpy(),
            metadata[name].to_numpy(),
        ):
            raise ValueError(f"V1 metadata mismatch: {name}")

    frame["patient_id"] = metadata["patient_id"].to_numpy()

    if frame["patient_id"].isna().any():
        raise ValueError("V1 dataset has missing patient IDs")

    for name in FEATURE_COLUMNS:
        if not pd.api.types.is_numeric_dtype(frame[name]):
            raise ValueError(f"Non-numeric V1 feature: {name}")

    if not np.isfinite(
        frame[FEATURE_COLUMNS].to_numpy(dtype=float)
    ).all():
        raise ValueError("V1 contains non-finite features")

    frame["split"] = frame["strat_fold"].map(split_name)

    if frame.groupby("patient_id")["split"].nunique().gt(1).any():
        raise ValueError("V1 has cross-partition patient leakage")

    partitions = {
        name: frame.loc[frame["split"] == name].copy()
        for name in ("train", "validation", "test")
    }

    for name, subset in partitions.items():
        if subset.empty or subset["target_label"].nunique() != 2:
            raise ValueError(f"Invalid V1 {name} partition")

    return partitions


def load_v3_candidate():
    """Verify the V3 dataset and the previously trained checkpoint."""

    if not V3_REPORT.is_file() or not V3_MODEL.is_file():
        raise FileNotFoundError("V3 candidate model or contract is missing")

    report = json.loads(V3_REPORT.read_text(encoding="utf-8"))

    if report.get("contract_version") != "rf_v3_research_candidate_v1":
        raise ValueError("Unsupported V3 model contract")

    if report.get("sqi_version") != "v3":
        raise ValueError("Incorrect V3 model SQI version")

    if report.get("feature_order") != FEATURE_COLUMNS:
        raise ValueError("V3 model feature schema differs")

    if report.get("class_order") != [0, 1]:
        raise ValueError("V3 model class order differs")

    if report.get("test", {}).get("evaluated") is not False:
        raise ValueError("V3 report does not preserve test reservation")

    artifacts = report["artifacts"]

    expected_hashes = (
        ("candidate_model_sha256", V3_MODEL),
        ("training_dataset_sha256", V3_DATASET),
        ("dataset_contract_sha256", V3_DATASET_CONTRACT),
    )

    for name, path in expected_hashes:
        if artifacts.get(name) != sha256_file(path):
            raise ValueError(f"V3 provenance mismatch: {name}")

    dataset_contract = verify_contract()

    frame = pd.read_csv(V3_DATASET)
    partitions = verify_dataset(frame, dataset_contract)

    # Load only the trusted checkpoint generated by our own project.
    model = joblib.load(V3_MODEL)

    if list(model.feature_names_in_) != FEATURE_COLUMNS:
        raise ValueError("V3 checkpoint feature order mismatch")

    if list(model.classes_) != [0, 1]:
        raise ValueError("V3 checkpoint class order mismatch")

    return model, partitions, report


def paired_validation(v1, v3):
    """Align validation records by ECG ID and verify their labels."""

    for name, frame in (("V1", v1), ("V3", v3)):
        required = {"ecg_id", "patient_id", "target_label"}

        if not required.issubset(frame.columns):
            raise ValueError(f"{name} validation metadata missing")

        if frame["ecg_id"].isna().any() or not frame["ecg_id"].is_unique:
            raise ValueError(f"{name} validation IDs are invalid")

    common_ids = sorted(
        set(v1["ecg_id"]) & set(v3["ecg_id"])
    )

    if not common_ids:
        raise ValueError("No shared V1/V3 validation ECGs")

    left = v1.set_index("ecg_id").loc[common_ids]
    right = v3.set_index("ecg_id").loc[common_ids]

    if not np.array_equal(
        left["target_label"].to_numpy(),
        right["target_label"].to_numpy(),
    ):
        raise ValueError("Paired diagnostic labels differ")

    if not np.array_equal(
        left["patient_id"].astype(str).to_numpy(),
        right["patient_id"].astype(str).to_numpy(),
    ):
        raise ValueError("Paired patient IDs differ")

    if set(left["target_label"]) != {0, 1}:
        raise ValueError("Paired cohort must contain both classes")

    return left, right


def validation_coverage(manifest, v1, v3):
    """Measure accepted cases by diagnostic class on fold 9."""

    population = manifest.loc[
        manifest["strat_fold"] == 9
    ]

    results = []

    for label in (0, 1):
        pool = set(
            population.loc[
                population["target_label"] == label, "ecg_id"
            ]
        )

        v1_ids = set(
            v1.loc[v1["target_label"] == label, "ecg_id"]
        )

        v3_ids = set(
            v3.loc[v3["target_label"] == label, "ecg_id"]
        )

        if not pool or not v1_ids <= pool or not v3_ids <= pool:
            raise ValueError("Validation selection is inconsistent")

        results.append({
            "target_label": label,
            "manifest_records": len(pool),
            "v1_accepted": len(v1_ids),
            "v3_eligible": len(v3_ids),
            "paired_records": len(v1_ids & v3_ids),
            "v1_coverage": len(v1_ids) / len(pool),
            "v3_coverage": len(v3_ids) / len(pool),
        })

    return results


def main():
    """Train a matched-method V1 comparator and evaluate fold 9."""

    outputs = (V1_MODEL, REPORT, PREDICTIONS)

    if any(path.exists() for path in outputs):
        raise FileExistsError(
            "Comparator artifacts already exist; refusing to overwrite"
        )

    v1 = load_v1_partitions()
    v3_model, v3, v3_report = load_v3_candidate()

    print("\nCardioSense | Matched V1 vs V3 RF Validation")
    print(f"V1 training ECGs : {len(v1['train'])}")
    print(f"V3 training ECGs : {len(v3['train'])}")
    print("Calibration      : same patient-aware 5-fold procedure")
    print("Evaluation       : fold 9 only")

    # Reuse the exact RF and calibration implementation from V3.
    v1_model, v1_full_metrics = train_candidate(v1)

    v3_full_probs = v3_model.predict_proba(
        v3["validation"][FEATURE_COLUMNS]
    )[:, 1]

    v3_full_metrics = calculate_metrics(
        v3["validation"]["target_label"],
        v3_full_probs,
    )

    # Compare only ECG IDs accepted by both selection policies.
    left, right = paired_validation(
        v1["validation"],
        v3["validation"],
    )

    p_v1 = v1_model.predict_proba(
        left[FEATURE_COLUMNS]
    )[:, 1]

    p_v3 = v3_model.predict_proba(
        right[FEATURE_COLUMNS]
    )[:, 1]

    labels = left["target_label"].to_numpy()

    matched_v1_metrics = calculate_metrics(labels, p_v1)
    matched_v3_metrics = calculate_metrics(labels, p_v3)

    predictions = pd.DataFrame({
        "ecg_id": left.index.to_numpy(),
        "patient_id": left["patient_id"].to_numpy(),
        "target_label": labels,
        "v1_probability": p_v1,
        "v3_probability": p_v3,
        "v1_prediction": (p_v1 >= 0.5).astype(int),
        "v3_prediction": (p_v3 >= 0.5).astype(int),
    })

    coverage = validation_coverage(
        pd.read_csv(MANIFEST),
        v1["validation"],
        v3["validation"],
    )

    V1_MODEL.parent.mkdir(parents=True, exist_ok=True)
    REPORT.parent.mkdir(parents=True, exist_ok=True)

    # Save only new comparator artifacts.
    temp_model = V1_MODEL.with_name(V1_MODEL.name + ".tmp")
    joblib.dump(v1_model, temp_model)
    temp_model.replace(V1_MODEL)

    temp_predictions = PREDICTIONS.with_name(
        PREDICTIONS.name + ".tmp"
    )
    predictions.to_csv(temp_predictions, index=False)
    temp_predictions.replace(PREDICTIONS)

    report = {
        "contract_version": "v1_v3_matched_fold9_v1",
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "git_commit": git_commit(),
        "evaluation_fold": 9,
        "test_fold_evaluated": False,
        "training_method": (
            "RandomForestClassifier + patient-aware "
            "StratifiedGroupKFold sigmoid calibration"
        ),
        "feature_order": FEATURE_COLUMNS,
        "training_records": {
            "v1": len(v1["train"]),
            "v3": len(v3["train"]),
        },
        "validation_full": {
            "v1": v1_full_metrics,
            "v3": v3_full_metrics,
        },
        "validation_matched": {
            "v1": matched_v1_metrics,
            "v3": matched_v3_metrics,
        },
        "coverage_by_label": coverage,
        "artifacts": {
            "v1_dataset_sha256": sha256_file(V1_DATASET),
            "v3_dataset_sha256": sha256_file(V3_DATASET),
            "v1_comparator_sha256": sha256_file(V1_MODEL),
            "v3_candidate_sha256": sha256_file(V3_MODEL),
            "v3_training_contract_sha256": sha256_file(V3_REPORT),
            "paired_predictions_sha256": sha256_file(PREDICTIONS),
        },
        "limitations": [
            "Models were trained on differently selected populations",
            "Matched validation does not isolate SQI's causal effect",
            "Small validation cohort; uncertainty remains high",
            "Fold 9 has been used during project development",
            "No clinical or external validation",
        ],
    }

    temp_report = REPORT.with_name(REPORT.name + ".tmp")
    temp_report.write_text(
        json.dumps(report, indent=2, allow_nan=False) + "\n",
        encoding="utf-8",
    )
    temp_report.replace(REPORT)

    print("\nFull fold-9 ROC-AUC")
    print(f"V1 comparator : {v1_full_metrics['roc_auc']:.4f}")
    print(f"V3 candidate  : {v3_full_metrics['roc_auc']:.4f}")

    print("\nMatched fold-9 results")
    print(f"Paired ECGs   : {len(left)}")

    for name in (
        "accuracy", "sensitivity", "specificity",
        "roc_auc", "pr_auc", "brier", "log_loss",
    ):
        a = matched_v1_metrics[name]
        b = matched_v3_metrics[name]
        print(f"{name:13s} V1={a:.4f}  V3={b:.4f}")

    print("\nValidation coverage by label")
    for item in coverage:
        print(
            f"Label {item['target_label']}: "
            f"manifest={item['manifest_records']}, "
            f"V1={item['v1_accepted']}, "
            f"V3={item['v3_eligible']}, "
            f"paired={item['paired_records']}"
        )

    print("\nSaved")
    print(f"V1 model   : {V1_MODEL}")
    print(f"Predictions: {PREDICTIONS}")
    print(f"Report     : {REPORT}")
    print("Fold 10    : not evaluated")
    print("Deployed checkpoints: unchanged")


if __name__ == "__main__":
    main()
